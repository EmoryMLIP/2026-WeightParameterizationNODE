#!/usr/bin/env python3
r"""Emit figures/weight_trajectories.tex: learned weights K(t) against time.

Reads results/weight_trajectories.mat, written by
matlab/analysis/exportWeightTrajectories.m from the raw records of the
paper sweep: the ResNet at T=1 under Adam, degree-3 Legendre and unconstrained,
CDR and DCR, ten seeds. The figure draws every entry of K(t) for one seed; the
header records two per-seed measures over all ten:

  time-varying share   ||K - mean_t K||_F / ||K||_F
  roughness            ||second difference of K in t||_F / ||K||_F

Usage: python3 export_weight_figure.py
"""
import os
import statistics as st

import numpy as np
import scipy.io as sio

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SEED_DRAWN = 20
DATASETS = ('ELM', 'CDR', 'DCR')
# Rows are the two models, columns the datasets, so a column shares one scale.
PANELS = [(ds, basis, '%s, %s' % (ds, 'Legendre $D=3$' if basis == 'Legendre' else 'unconstrained'))
          for basis in ('Legendre', 'none') for ds in DATASETS]


def measures(K):
    nrm = np.linalg.norm(K)
    return (np.linalg.norm(K - K.mean(axis=1, keepdims=True)) / nrm,
            np.linalg.norm(np.diff(K, 2, axis=1)) / nrm)


def main():
    m = sio.loadmat(os.path.join(ROOT, 'results', 'weight_trajectories.mat'),
                    squeeze_me=True, struct_as_record=False)
    runs = {(o.dataset, o.basis, int(o.seed)): o for o in m['out']}
    seeds = sorted({s for (_, _, s) in runs})

    notes = []
    for ds, basis, _ in PANELS:
        tv, r2 = zip(*(measures(np.atleast_2d(runs[(ds, basis, s)].K)) for s in seeds))
        notes.append('%%   %s %-8s time-varying share %.3f-%.3f, roughness %.3f-%.3f (%d seeds)'
                     % (ds, basis, min(tv), max(tv), min(r2), max(r2), len(seeds)))
    for ds in DATASETS:
        q = [measures(np.atleast_2d(runs[(ds, 'none', s)].K))[1]
             / measures(np.atleast_2d(runs[(ds, 'Legendre', s)].K))[1] for s in seeds]
        notes.append('%%   %s roughness unconstrained/Legendre per seed %.2f-%.2f, median %.2f, >1 on %d/%d'
                     % (ds, min(q), max(q), st.median(q), sum(x > 1 for x in q), len(q)))

    body = []
    for k, (ds, basis, title) in enumerate(PANELS):
        o = runs[(ds, basis, SEED_DRAWN)]
        K = np.atleast_2d(o.K)
        # One y-range per dataset, so the two models of a row are read on one scale.
        lo, hi = (min(np.atleast_2d(runs[(ds, b, SEED_DRAWN)].K).min() for b in ('Legendre', 'none')),
                  max(np.atleast_2d(runs[(ds, b, SEED_DRAWN)].K).max() for b in ('Legendre', 'none')))
        pad = 0.05 * (hi - lo)
        opts = 'title={%s},ymin=%.4f,ymax=%.4f' % (title, lo - pad, hi + pad)
        if k >= 3:
            opts += ',xlabel={time $t$}'
        if k % 3 == 0:
            opts += ',ylabel={entries of $\\mathbf{K}(t)$}'
        body.append('\\nextgroupplot[%s]' % opts)
        for row in K:
            body.append('\\addplot[black,opacity=0.35,line width=0.4pt] coordinates {%s};'
                        % ' '.join('(%.4f,%.5f)' % (t, v) for t, v in zip(o.t, row)))

    out = os.path.join(ROOT, 'figures', 'weight_trajectories.tex')
    with open(out, 'w') as fh:
        fh.write('%% generated by python/export_weight_figure.py\n')
        fh.write('%% source: results/weight_trajectories.mat (%s)\n' % str(m['prov']).strip())
        fh.write('%% every entry of K(t), ResNet, T=1, Adam, seed %d drawn; measures over all seeds\n'
                 % SEED_DRAWN)
        fh.write('\n'.join(notes) + '\n')
        fh.write(r"""\documentclass[tikz]{standalone}
\usepackage{pgfplots}
\usepgfplotslibrary{groupplots}
\pgfplotsset{compat=1.18}
\begin{document}
\begin{tikzpicture}
\begin{groupplot}[group style={group size=3 by 2,horizontal sep=1.15cm,vertical sep=1.3cm},
  width=1.95in,height=1.6in,xmin=0,xmax=1,
  title style={font=\small},tick label style={font=\footnotesize},
  label style={font=\small}]
""")
        fh.write('\n'.join(body) + '\n')
        fh.write('\\end{groupplot}\n\\end{tikzpicture}\n\\end{document}\n')
    print('wrote', out)
    for line in notes:
        print(line[2:])


if __name__ == '__main__':
    main()
