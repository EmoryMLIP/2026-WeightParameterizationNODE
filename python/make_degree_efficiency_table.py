#!/usr/bin/env python3
"""Emit tables/table2.tex: what the degree buys, as three tests.

Reads results/runs.csv (override with RUNS_CSV). Every comparison is paired
within a seed: a seed fixes the initialization of all twelve degrees and of the
unconstrained model, and log test error is correlated within a seed across them,
so pairing raises power. Errors are compared on the log scale because they are
positive and their spread grows with their size.

  Within 10%   Does a degree reach the unconstrained model's test error with
               fewer parameters? A degree qualifies when the upper end of the
               95% interval of test(D)/test(unconstrained) lies below
               1 + MARGIN. The smallest qualifying degree is reported.
  Contrast     Test error at D=11 over D=0, paired, with its 95% interval.
  Trend        Does test error change monotonically with degree? Page's L test
               over D = 0..11 with seeds as blocks. The fitted slope is
               descriptive only: residuals within a seed are correlated across
               degrees and several curves are U-shaped.
  Selection    Which degree would a user with one run pick? Per seed, the
               degree with the lowest validation error, reported as the median
               and range of those choices and the geometric-mean test error they
               give. Choosing the degree with the lowest mean test error over
               twelve degrees would be biased toward a difference.

Usage: python3 make_degree_efficiency_table.py
"""
import csv
import math
import os
import statistics as st
import subprocess
import sys
from collections import defaultdict

from paired_stats import page_trend, paired, per_seed_slopes
from sweep_defaults import degree_axis_sweeps, is_default_run

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))

MARGIN = 0.10
DATASETS = ['ELM', 'CDR', 'DCR']
ARCHS = [('ResNN', 'ResNet'), ('hamiltonian', 'Hamiltonian')]
OPTIS = [('sgd', 'Adam'), ('GNvpro', 'GNvpro')]


def load():
    """(dataset, dynamic, opti, arm) -> {seed: (test, val)}; arm is a degree or 'unc'."""
    cells, par = defaultdict(dict), {}
    with open(os.environ.get('RUNS_CSV') or os.path.join(ROOT, 'results', 'runs.csv')) as fh:
        for r in csv.DictReader(fh):
            if (r['sweep'] not in degree_axis_sweeps(r['opti']) or r['T'] != '1'
                    or r['precision'] != 'double' or float(r['alpha1']) != 1e-10
                    or not is_default_run(r)):
                continue
            if r['basis'] == 'none':
                arm = 'unc'
            elif r['basis'] == 'Legendre':
                arm = int(float(r['d']))
            else:
                continue
            key = (r['dataset'], r['dynamic'], r['opti'], arm)
            assert r['seed'] not in cells[key], f'seed {r["seed"]} twice in {key}'
            cells[key][r['seed']] = (float(r['test_agg']), float(r['val_agg']))
            par[(r['dataset'], arm)] = int(r['nParamsDynamics'])
    if not cells:
        sys.exit('no degree-axis runs in the ledger')
    return cells, par


def gmean(v):
    return math.exp(st.mean(math.log(x) for x in v))


def analyze(cells, ds, arch, opti):
    test = {d: {s: t for s, (t, _) in cells[(ds, arch, opti, d)].items()} for d in list(range(12)) + ['unc']}
    val = {d: {s: v for s, (_, v) in cells[(ds, arch, opti, d)].items()} for d in range(12)}
    bounds = {d: paired(test[d], test['unc']) for d in range(12)}
    noninf = [d for d in range(12) if bounds[d]['hi'] < 1 + MARGIN]
    z, pz = page_trend([test[d] for d in range(12)])
    seeds = sorted(set.intersection(*(set(val[d]) for d in range(12))))
    pick = {s: min(range(12), key=lambda d: val[d][s]) for s in seeds}
    return dict(n=bounds[11]['n'], bounds=bounds, noninf=noninf, c=paired(test[11], test[0]),
                z=z, pz=pz, slope=per_seed_slopes([test[d] for d in range(12)], list(range(12))),
                picks=sorted(pick.values()), selerr=gmean([test[pick[s]][s] for s in seeds]))


def main():
    cells, par = load()
    commit = subprocess.check_output(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD'],
                                     text=True).strip()
    rows = []
    for opti, olab in OPTIS:
        for ds in DATASETS:
            for arch, alab in ARCHS:
                if any((ds, arch, opti, d) not in cells for d in list(range(12)) + ['unc']):
                    continue
                rows.append(dict(opti=olab, ds=ds, arch=alab, pu=par[(ds, 'unc')], **analyze(cells, ds, arch, opti)))

    out = os.path.join(ROOT, 'tables', 'table2.tex')
    with open(out, 'w') as fh:
        fh.write('%% generated by python/make_degree_efficiency_table.py at commit %s\n' % commit)
        fh.write('%% sweeps: Adam %s; GNvpro %s\n' % (', '.join(sorted(degree_axis_sweeps('sgd'))),
                                                    ', '.join(sorted(degree_axis_sweeps('GNvpro')))))
        fh.write('%% paired by seed on log test error; the smallest degree within %.0f%% of the\n'
                 '%% unconstrained model is the smallest whose 95%% interval lies below that\n'
                 '%% margin; the last column is the per-seed slope of log test error in\n'
                 '%% degree, as percent per degree\n' % (100 * MARGIN))
        fh.write('\\begin{tabular}{llccccc}\n\\toprule\n')
        fh.write('& & & \\multicolumn{2}{c}{validation choice} & smallest $D$ & slope \\\\\n')
        fh.write('\\cmidrule(lr){4-5}\n')
        fh.write('Optimizer & Dataset & Architecture & $D$ & test error '
                 '& within $10\\%$ '
                 '& \\% per degree \\\\\n\\midrule\n')
        last = None
        for r in rows:
            lead = r['opti'] if r['opti'] != last else ''
            last = r['opti']
            if r['noninf']:
                k = min(r['noninf'])
                ni = ('$%d$ ($%.2g\\times$, $%.2f$)'
                      % (k, r['pu'] / par[(r['ds'], k)], r['bounds'][k]['hi']))
            else:
                ni = 'none ($%.2f$)' % r['bounds'][11]['hi']
            sl = r['slope']
            # One decimal on the slope and two significant digits on the error.
            fh.write('%s & %s & %s & $%d$ ($%d$--$%d$) & $%#.2g$ & %s '
                     '& $%+.1f$ [$%+.1f$, $%+.1f$] \\\\\n'
                     % (lead, r['ds'], r['arch'],
                        st.median_low(r['picks']), r['picks'][0], r['picks'][-1], r['selerr'],
                        ni, sl['pct'], sl['lo'], sl['hi']))
        fh.write('\\botrule\n\\end{tabular}\n')
    print('wrote %s (%d rows)' % (out, len(rows)))
    for r in rows:
        b = ' '.join('%.2f' % r['bounds'][d]['hi'] for d in range(12))
        c, sl = r['c'], r['slope']
        print('  %-6s %s %-11s n=%d  within 10%% %s' % (r['opti'], r['ds'], r['arch'], r['n'], r['noninf'] or 'none'))
        print('      bounds D0..11: %s' % b)
        print('      D11/D0 %.3f [%.3f, %.3f] p %.4f | per-seed slope %+.2f%% [%+.2f, %+.2f] '
              '| Page z %+.2f p %.2g (diagnostic only)'
              % (c['ratio'], c['lo'], c['hi'], c['p'], sl['pct'], sl['lo'], sl['hi'], r['z'], r['pz']))
        print('      D vs unconstrained ratios: %s' % ' '.join('%.2f' % r['bounds'][d]['ratio'] for d in range(12)))
        print('      val picks %s  geo test %.4f' % (r['picks'], r['selerr']))


if __name__ == '__main__':
    main()
